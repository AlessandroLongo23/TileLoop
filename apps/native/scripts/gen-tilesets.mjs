// Generates apps/native/assets/tilesets.gen.ts: a map of "tileset/sides/connections"
// -> raw SVG string, so Metro bundles all tile art into the native app (there is
// no runtime fetch of static files on device).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
// Canonical tileset source is the web app's public dir (served on web, bundled here).
const tilesetsDir = join(repoRoot, 'apps', 'web', 'public', 'tilesets');
const outFile = join(here, '..', 'assets', 'tilesets.gen.ts');

const entries = {};
for (const tileset of readdirSync(tilesetsDir)) {
  const tilesetDir = join(tilesetsDir, tileset);
  for (const sides of readdirSync(tilesetDir)) {
    const sidesDir = join(tilesetDir, sides);
    for (const file of readdirSync(sidesDir)) {
      if (!file.endsWith('.svg')) continue;
      const connections = file.replace(/\.svg$/, '');
      const svg = readFileSync(join(sidesDir, file), 'utf8').trim();
      entries[`${tileset}/${sides}/${connections}`] = svg;
    }
  }
}

const body = Object.entries(entries)
  .map(([key, svg]) => `  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/gen-tilesets.mjs — do not edit.
export const tilesets: Record<string, string> = {
${body}
};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`Wrote ${Object.keys(entries).length} tilesets to ${outFile}`);
